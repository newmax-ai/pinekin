    fireEvent.click(screen.getByRole('button', { name: '选择其他文件夹' }))
    await screen.findByRole('alert')
    expect(screen.queryByRole('button', { name: '在 project 重试' })).toBeNull()
    expect(screen.queryByRole('button', { name: '接续设置' })).toBeNull()
    expect(screen.getByRole('button', { name: '选择其他文件夹' })).toBeTruthy()
