    const alert = await screen.findByRole('alert')
    expect(alert.textContent).toContain('请重试')
    expect(alert.textContent).not.toMatch(/Error invoking|pinekin:|查看更新后重新阅读/)
    expect(screen.queryByRole('button', { name: '接续设置' })).toBeNull()
