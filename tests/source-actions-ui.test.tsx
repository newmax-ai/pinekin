    const api = enableTarget()
    vi.mocked(api.listCodexProjects!).mockRejectedValueOnce(new Error('合成项目列表读取失败'))
    render(<SourceActions {...props} />); await openTargets()
    expect(await screen.findByText('合成项目列表读取失败')).toBeTruthy()
