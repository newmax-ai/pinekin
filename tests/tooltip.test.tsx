// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react'
import { DsButton } from '../src/renderer/src/components/ui'

const advance = (ms = 150) => act(() => vi.advanceTimersByTime(ms))
const button = () => screen.getByRole('button', { name: '导入会话文件' })
const renderButton = () => render(<DsButton iconOnly aria-label="导入会话文件">+</DsButton>)
beforeEach(() => { vi.useFakeTimers(); vi.setSystemTime(new Date('2026-10-17T12:00:00Z')) })
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.useRealTimers() })

describe('NewMax 图标按钮提示适配', () => {
  it('悬停 150ms 后显示语义提示，不增加布局包装或原生 title', () => {
    const { container } = renderButton()
    expect(container.firstElementChild).toBe(button())
    expect(button().hasAttribute('title')).toBe(false)
    expect(screen.queryByRole('tooltip')).toBeNull()
    fireEvent.mouseEnter(button())
    advance(149)
    expect(screen.queryByRole('tooltip')).toBeNull()
    advance(1)
    const tooltip = screen.getByRole('tooltip')
    expect(tooltip.textContent).toBe('导入会话文件')
    expect(button().getAttribute('aria-describedby')).toBe(tooltip.id)
    expect(tooltip.parentElement).toBe(document.body)
    fireEvent.mouseLeave(button())
    expect(screen.queryByRole('tooltip')).toBeNull()
    expect(button().hasAttribute('aria-describedby')).toBe(false)
  })
  it('离开、按下或卸载取消尚未显示的提示', () => {
    for (const action of ['leave', 'press', 'unmount']) {
      const view = renderButton()
      fireEvent.mouseEnter(button())
      if (action === 'leave') fireEvent.mouseLeave(button())
      if (action === 'press') fireEvent.pointerDown(button())
      if (action === 'unmount') view.unmount()
      advance(500)
      expect(screen.queryByRole('tooltip')).toBeNull()
      view.unmount()
    }
  })
  it('键盘聚焦立即提示，失焦和 Escape 收起且不吞掉 Escape', () => {
    const onKeyDown = vi.fn()
    render(<div onKeyDown={onKeyDown}><DsButton iconOnly aria-label="导入会话文件">+</DsButton></div>)
    fireEvent.focus(button())
    expect(screen.getByRole('tooltip').textContent).toBe('导入会话文件')
    fireEvent.keyDown(button(), { key: 'Escape' })
    expect(screen.queryByRole('tooltip')).toBeNull()
    expect(onKeyDown).toHaveBeenCalledOnce()
    fireEvent.blur(button())
    fireEvent.focus(button())
    fireEvent.blur(button())
    expect(screen.queryByRole('tooltip')).toBeNull()
  })
  it.each(['click', 'pointerDown', 'scroll', 'blur'])('%s 关闭已显示的提示', action => {
    renderButton()
    fireEvent.focus(button())
    expect(screen.getByRole('tooltip')).toBeTruthy()
    if (action === 'click') fireEvent.click(button())
    if (action === 'pointerDown') fireEvent.pointerDown(button())
    if (action === 'scroll') fireEvent.scroll(window)
    if (action === 'blur') fireEvent(window, new Event('blur'))
    expect(screen.queryByRole('tooltip')).toBeNull()
  })
  it('始终只显示一个提示，300ms 内跨按钮悬停跳过延迟', () => {
    render(<><DsButton iconOnly aria-label="导入会话文件">+</DsButton><DsButton iconOnly aria-label="搜索">?</DsButton></>)
    fireEvent.mouseEnter(button())
    advance()
    fireEvent.mouseLeave(button())
    fireEvent.mouseEnter(screen.getByRole('button', { name: '搜索' }))
    expect(screen.getAllByRole('tooltip').map(item => item.textContent)).toEqual(['搜索'])
    fireEvent.focus(button())
    expect(screen.getAllByRole('tooltip').map(item => item.textContent)).toEqual(['导入会话文件'])
  })
  it('禁用、拖拽和带文字操作不显示提示', () => {
    const view = render(<DsButton iconOnly disabled aria-label="导入会话文件">+</DsButton>)
    fireEvent.mouseEnter(button()); advance()
    expect(screen.queryByRole('tooltip')).toBeNull()
    view.rerender(<DsButton iconOnly aria-label="导入会话文件">+</DsButton>)
    fireEvent.mouseEnter(button(), { buttons: 1 }); advance()
    expect(screen.queryByRole('tooltip')).toBeNull()
    fireEvent.mouseEnter(button()); advance()
    expect(screen.getByRole('tooltip')).toBeTruthy()
    view.rerender(<DsButton iconOnly disabled aria-label="导入会话文件">+</DsButton>)
    expect(screen.queryByRole('tooltip')).toBeNull()
    view.rerender(<DsButton title="原生文字说明">导入会话文件</DsButton>)
    fireEvent.mouseEnter(button()); advance()
    expect(screen.queryByRole('tooltip')).toBeNull()
    expect(button().title).toBe('原生文字说明')
  })
  it('鼠标按下后聚焦不闪现提示，重新悬停和键盘聚焦仍正常显示', () => {
    renderButton()
    fireEvent.mouseEnter(button()); advance()
    expect(screen.getByRole('tooltip')).toBeTruthy()
    fireEvent.pointerDown(button()); fireEvent.focus(button())
    expect(screen.queryByRole('tooltip')).toBeNull()
    advance(500)
    expect(screen.queryByRole('tooltip')).toBeNull()
    fireEvent.mouseLeave(button()); fireEvent.mouseEnter(button()); advance()
    expect(screen.getByRole('tooltip')).toBeTruthy()
    fireEvent.blur(button()); fireEvent.focus(button())
    expect(screen.getByRole('tooltip')).toBeTruthy()
  })
  it.each([undefined, false, 'false'] as const)('展开的非弹层控件仍显示提示（aria-haspopup=%s）', hasPopup => {
    render(<DsButton iconOnly aria-label="收起侧栏" aria-expanded={true} aria-haspopup={hasPopup}>侧栏</DsButton>)
    fireEvent.focus(screen.getByRole('button', { name: '收起侧栏' }))
    expect(screen.getByRole('tooltip').textContent).toBe('收起侧栏')
  })
  it('展开的菜单触发器不显示提示，并取消已有提示和延迟任务', () => {
    const control = (expanded: boolean) => <DsButton iconOnly aria-label="导入会话文件" aria-haspopup="menu" aria-expanded={expanded}>+</DsButton>
    const view = render(control(false))
    fireEvent.mouseEnter(button())
    view.rerender(control(true)); advance()
    expect(screen.queryByRole('tooltip')).toBeNull()
    fireEvent.focus(button()); fireEvent.mouseEnter(button()); advance()
    expect(screen.queryByRole('tooltip')).toBeNull()
    view.rerender(control(false)); advance()
    expect(screen.queryByRole('tooltip')).toBeNull()
    fireEvent.mouseLeave(button()); fireEvent.mouseEnter(button()); advance()
    expect(screen.getByRole('tooltip')).toBeTruthy()
    view.rerender(control(true))
    expect(screen.queryByRole('tooltip')).toBeNull()
    expect(button().hasAttribute('aria-describedby')).toBe(false)
    view.rerender(control(false))
    expect(screen.queryByRole('tooltip')).toBeNull()
  })
  it('保留原事件、ref 和既有描述，标题退回为图标提示而不出现双重气泡', () => {
    const onMouseEnter = vi.fn(), onFocus = vi.fn(), onBlur = vi.fn(), onClick = vi.fn(), onPointerDown = vi.fn()
    const ref = { current: null as HTMLButtonElement | null }
    render(<DsButton iconOnly ref={ref} title="导入会话文件" aria-label="导入会话文件" aria-describedby="help" onMouseEnter={onMouseEnter} onFocus={onFocus} onBlur={onBlur} onClick={onClick} onPointerDown={onPointerDown}>+</DsButton>)
    expect(ref.current).toBe(button())
    fireEvent.mouseEnter(button()); advance()
    expect(onMouseEnter).toHaveBeenCalledOnce()
    expect(button().getAttribute('aria-describedby')).toBe(`help ${screen.getByRole('tooltip').id}`)
    fireEvent.focus(button()); fireEvent.blur(button()); fireEvent.pointerDown(button()); fireEvent.click(button())
    for (const handler of [onFocus, onBlur, onClick, onPointerDown]) expect(handler).toHaveBeenCalledOnce()
    expect(button().getAttribute('aria-describedby')).toBe('help')
    expect(button().hasAttribute('title')).toBe(false)
  })
  it('同一按钮从悬停切到键盘聚焦不重置位置或隐藏提示', () => {
    renderButton()
    fireEvent.mouseEnter(button()); advance()
    const tooltip = screen.getByRole('tooltip')
    const position = tooltip.style.cssText
    fireEvent.focus(button())
    expect(screen.getByRole('tooltip')).toBe(tooltip)
    expect(tooltip.style.cssText).toBe(position)
  })
  it('动态操作名称更新，提示内容作为文本而非 HTML 渲染', () => {
    const view = renderButton()
    fireEvent.focus(button())
    view.rerender(<DsButton iconOnly aria-label="<img src=x onerror=alert(1)>">+</DsButton>)
    const tooltip = screen.getByRole('tooltip')
    expect(tooltip.textContent).toBe('<img src=x onerror=alert(1)>')
    expect(tooltip.querySelector('img')).toBeNull()
  })
  it('顶部按钮向下定位，靠右时按 8px 安全边距平移，底部空间不足时翻转', () => {
    vi.spyOn(HTMLElement.prototype, 'offsetWidth', 'get').mockReturnValue(120)
    vi.spyOn(HTMLElement.prototype, 'offsetHeight', 'get').mockReturnValue(32)
    const view = renderButton()
    vi.spyOn(button(), 'getBoundingClientRect').mockReturnValue({ left: window.innerWidth - 35, right: window.innerWidth, top: 5, bottom: 33, width: 35, height: 28 } as DOMRect)
    fireEvent.focus(button())
    expect(screen.getByRole('tooltip').style.top).toBe('37px')
    expect(screen.getByRole('tooltip').style.left).toBe(`${window.innerWidth - 128}px`)
    view.unmount()
    renderButton()
    vi.spyOn(button(), 'getBoundingClientRect').mockReturnValue({ left: 0, right: 35, top: window.innerHeight - 28, bottom: window.innerHeight, width: 35, height: 28 } as DOMRect)
    fireEvent.focus(button())
    expect(screen.getByRole('tooltip').style.top).toBe(`${window.innerHeight - 64}px`)
    expect(screen.getByRole('tooltip').style.left).toBe('8px')
  })
  it('使用原生顶层提示以覆盖 modal，卸载后清理顶层和定时器', () => {
    const show = vi.fn(function (this: HTMLElement) { this.style.display = 'block' }), hide = vi.fn()
    Object.defineProperty(HTMLElement.prototype, 'showPopover', { configurable: true, value: show })
    Object.defineProperty(HTMLElement.prototype, 'hidePopover', { configurable: true, value: hide })
    const view = renderButton()
    fireEvent.focus(button())
    expect(screen.getByRole('tooltip').getAttribute('popover')).toBe('manual')
    expect(show).toHaveBeenCalledOnce()
    view.unmount()
    expect(hide).toHaveBeenCalledOnce()
    expect(vi.getTimerCount()).toBe(0)
    delete (HTMLElement.prototype as Partial<HTMLElement>).showPopover
    delete (HTMLElement.prototype as Partial<HTMLElement>).hidePopover
  })
})
