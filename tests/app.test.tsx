  it('搜索仅点击外侧遮罩关闭，保留查询并返回搜索图标焦点', async () => {
    await open()
    const trigger = screen.getByRole('button', { name: '搜索' })
    trigger.focus()
    const input = openSearch()
    fireEvent.change(input, { target: { value: '安全边界' } })
    const dialog = screen.getByRole('dialog', { name: '搜索会话' })
    vi.spyOn(dialog, 'getBoundingClientRect').mockReturnValue(new DOMRect(100, 100, 600, 400))
    const pointerDown = (target: HTMLElement, clientX: number, clientY: number) =>
      fireEvent(target, new MouseEvent('pointerdown', { bubbles: true, clientX, clientY }))
    // 原生 dialog 的内部留白与外侧遮罩均可能以 dialog 为事件目标。
    pointerDown(dialog, 120, 120)
    fireEvent.click(dialog, { clientX: 120, clientY: 120 })
    pointerDown(input, 150, 150)
    fireEvent.click(input, { clientX: 150, clientY: 150 })
    expect(screen.getByRole('dialog', { name: '搜索会话' })).toBe(dialog)
    // 从内部选中文字再拖到遮罩释放，不等于点击遮罩。
    pointerDown(input, 150, 150)
    fireEvent.click(dialog, { clientX: 50, clientY: 50 })
    expect(screen.getByRole('dialog', { name: '搜索会话' })).toBe(dialog)
    pointerDown(dialog, 50, 50)
    fireEvent.click(dialog, { clientX: 50, clientY: 50 })
    expect(screen.queryByRole('dialog')).toBeNull()
    await waitFor(() => expect(document.activeElement).toBe(trigger))
    expect(openSearch().value).toBe('安全边界')
    closeSearch()
  })
