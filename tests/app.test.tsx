    const nav = screen.getByRole('complementary', { name: '档案导航' })
    for (const [source, label] of [['newmax', 'NewMax'], ['claude-code', 'Claude Code'], ['codex', 'Codex'], ['cindy', 'Cindy'], ['deepseek', 'DeepSeek']] as const) {
      const button = within(nav).getByRole('button', { name: new RegExp(`^${label}`) })
      const icon = button.querySelector(`[data-source="${source}"] img`)
      expect(icon).not.toBeNull()
      const asset = new URL(icon!.getAttribute('src')!, window.location.href)
      // Vite 会把小图标内联为 data URL，大图标则使用同源资源路径。
      if (asset.protocol === 'data:') expect(asset.href).toMatch(/^data:image\/(?:svg\+xml|png)[;,]/)
      else {
        expect(asset.origin).toBe(window.location.origin)
        expect(asset.pathname).toContain('/assets/clients/')
      }
      expect(button.querySelector('.source-dot')).toBeNull()
    }
    expect(within(nav).getByRole('button', { name: /^其他来源/ }).querySelector('.source-icon svg')).not.toBeNull()
